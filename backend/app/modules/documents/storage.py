"""Where document bytes live, behind one small interface.

Local: encrypted files on disk (laptop and test VPS). S3 (private bucket, KMS encryption) is added with the AWS
setup by writing one more class with these three methods.
"""

import os
import re
import tempfile
from functools import lru_cache
from pathlib import Path
from typing import Protocol

from app.core.config import get_settings
from app.core.crypto import decrypt_bytes, encrypt_bytes

_KEY = re.compile(r"^\d{4}/\d{2}/[0-9a-f-]{36}$")  # keys are generated by us; refuse anything else


class DocumentStorage(Protocol):
    def put(self, key: str, data: bytes) -> None: ...
    def get(self, key: str) -> bytes: ...
    def delete(self, key: str) -> None: ...


class LocalEncryptedStorage:
    def __init__(self, root: str | Path):
        self.root = Path(root)

    def _path(self, key: str) -> Path:
        if not _KEY.match(key):
            raise ValueError(f"Bad storage key: {key!r}")
        return self.root / f"{key}.enc"

    def put(self, key: str, data: bytes) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        # Write to a temp file and rename, so a crash never leaves half a file behind.
        fd, tmp = tempfile.mkstemp(dir=path.parent)
        try:
            with os.fdopen(fd, "wb") as f:
                f.write(encrypt_bytes(data))
            os.replace(tmp, path)
        except BaseException:
            Path(tmp).unlink(missing_ok=True)
            raise

    def get(self, key: str) -> bytes:
        return decrypt_bytes(self._path(key).read_bytes())

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)


@lru_cache
def get_document_storage() -> DocumentStorage:
    settings = get_settings()
    if settings.document_storage == "local":
        return LocalEncryptedStorage(settings.documents_dir)
    raise RuntimeError(f"Unknown DOCUMENT_STORAGE: {settings.document_storage}")

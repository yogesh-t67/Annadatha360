const norm = (s: string) => s.replace(/\s+/g, ' ').trim().toLowerCase();

type MarketKind = 'yard' | 'rythuBazar' | null;

function splitMarket(name: string): { town: string; kind: MarketKind } {
  let kind: MarketKind = null;
  let s = name.replace(/\s+/g, ' ');
  if (/rythu bazar|\bRBZ\b/i.test(s)) kind = 'rythuBazar';
  else if (/\bAPMC\b/i.test(s)) kind = 'yard';
  s = s
    .replace(/\(?\s*rythu bazar\s*\)?/gi, '')
    .replace(/,?\s*RBZ\b/gi, '')
    .replace(/\bAPMC\b/gi, '')
    .replace(/\(\s*\)/g, '')
    .replace(/^[\s,]+|[\s,]+$/g, '');
  return { town: s, kind };
}

const KIND_TE: Record<Exclude<MarketKind, null>, string> = {
  yard: 'మార్కెట్ యార్డు',
  rythuBazar: 'రైతు బజార్',
};

/** Market name in the farmer's language. English stays exactly as the feed sends it. */
export function marketName(name: string, lang: string): string {
  if (lang !== 'te') return name;
  const { town, kind } = splitMarket(name);
  const te = MARKET_TOWN_TE[norm(town)];
  if (!te) return name;
  return kind ? `${te} ${KIND_TE[kind]}` : te;
}

export function varietyName(variety: string, lang: string): string {
  if (lang !== 'te' || !variety) return variety;
  return VARIETY_TE[norm(variety)] ?? variety;
}

let feedDistricts: Map<string, DistrictKey> | null = null;

/**
 * Map a feed district name ("SPSR Nellore", "Mahbubnagar", "Guntur") to our district key.
 * `englishName` resolves our key to its English display name (from i18n).
 */
export function districtKeyForFeed(name: string, englishName: (key: DistrictKey) => string): DistrictKey | undefined {
  if (!feedDistricts) {
    feedDistricts = new Map();
    for (const d of districtList) {
      feedDistricts.set(norm(englishName(d.key)), d.key);
      if ('mandi' in d && d.mandi) feedDistricts.set(norm(d.mandi), d.key);
    }
  }
  return feedDistricts.get(norm(name));
}
